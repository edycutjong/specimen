#!/usr/bin/env node
// Who wrote the product code? Counts the lines ADDED to packages/, apps/ and servers/ in every commit, grouped by the
// commit-message prefix this repo uses: `kiro:` = the change came out of a Kiro session (its prompt is in prompts/),
// `claude-direct:` = glue, harnesses, fixes and the hollow-inn v1/v2 demo server written outside Kiro.
// Lines added, not net lines: a line rewritten later counts again for whoever rewrote it.
//   node scripts/authorship.mjs            → prints the table (Markdown)
//   node scripts/authorship.mjs --write    → also writes evidence/authorship.md
import { execFileSync } from "node:child_process";
import fs from "node:fs";

const DIRS = ["packages", "apps", "servers"];
const log = execFileSync("git", ["log", "--no-merges", "--format=%x00%h%x09%s", "--numstat", "--", ...DIRS], {
  encoding: "utf8",
  maxBuffer: 64 * 1024 * 1024,
});
const isTest = (f) => /(^|\/)(test|tests|__tests__)\/|\.test\.[cm]?[jt]sx?$/.test(f);
const rows = {}; // kind → { src, test, commits }
for (const block of log.split("\0")) {
  if (!block.trim()) continue;
  const [head, ...files] = block.trim().split("\n");
  const subject = head.split("\t")[1] ?? "";
  const kind = subject.startsWith("kiro:") ? "kiro:" : subject.startsWith("claude-direct") ? "claude-direct:" : "other";
  const r = (rows[kind] ??= { src: 0, test: 0, commits: 0 });
  r.commits += 1;
  for (const line of files) {
    const [added, , file] = line.split("\t");
    if (!file || added === "-") continue; // binary
    r[isTest(file) ? "test" : "src"] += Number(added);
  }
}
const kinds = ["kiro:", "claude-direct:", "other"].filter((k) => rows[k]);
const sum = (k) => rows[k].src + rows[k].test;
const total = kinds.reduce((n, k) => n + sum(k), 0);
const srcTotal = kinds.reduce((n, k) => n + rows[k].src, 0);
const pct = (a, b) => ((100 * a) / b).toFixed(1);
const fmt = (n) => n.toLocaleString("en-US");
const head = execFileSync("git", ["log", "-1", "--format=%h %cs"], { encoding: "utf8" }).trim();

const out = [
  `# Authorship of the product code, by commit prefix`,
  ``,
  `Generated by \`node scripts/authorship.mjs --write\` at ${head}. Scope: lines added to \`${DIRS.join("/`, `")}/\``,
  `in non-merge commits, grouped by the commit-message prefix (\`kiro:\` = output of a Kiro session, prompt in`,
  `\`prompts/\`; \`claude-direct:\` = written outside Kiro). Lines added, not net lines. Docs, evidence, \`.kiro/\`,`,
  `\`site/\` and \`scripts/\` are outside the scope.`,
  ``,
  `| prefix | commits | source lines added | test lines added | total | share |`,
  `|---|---|---|---|---|---|`,
  ...kinds.map((k) => `| ${k} | ${rows[k].commits} | ${fmt(rows[k].src)} | ${fmt(rows[k].test)} | ${fmt(sum(k))} | ${pct(sum(k), total)} % |`),
  `| all | ${kinds.reduce((n, k) => n + rows[k].commits, 0)} | ${fmt(srcTotal)} | ${fmt(total - srcTotal)} | ${fmt(total)} | 100 % |`,
  ``,
  `Source lines only: \`kiro:\` ${pct(rows["kiro:"].src, srcTotal)} % (${fmt(rows["kiro:"].src)} of ${fmt(srcTotal)}).`,
  ``,
].join("\n");
process.stdout.write(out);
if (process.argv.includes("--write")) fs.writeFileSync(new URL("../evidence/authorship.md", import.meta.url), out);
